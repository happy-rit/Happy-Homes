-- Happy Homes Hotel booking schema (Oracle Database 12c+)
-- Run this script as the application schema owner. Rates are example project values; update them before real use.
CREATE TABLE HH_ROOM_TYPES (
  ROOM_TYPE VARCHAR2(20) PRIMARY KEY,
  DISPLAY_NAME VARCHAR2(80) NOT NULL,
  TOTAL_ROOMS NUMBER(3) DEFAULT 1 NOT NULL CHECK (TOTAL_ROOMS > 0),
  NIGHTLY_RATE NUMBER(10,2) NOT NULL CHECK (NIGHTLY_RATE >= 0),
  MAX_GUESTS NUMBER(2) DEFAULT 2 NOT NULL CHECK (MAX_GUESTS BETWEEN 1 AND 6),
  CONSTRAINT HH_ROOM_TYPE_CODE_CK CHECK (ROOM_TYPE IN ('STANDARD','DELUXE','SUITE','FAMILY'))
);

CREATE TABLE HH_BOOKINGS (
  BOOKING_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  BOOKING_CODE VARCHAR2(20) NOT NULL UNIQUE,
  FULL_NAME VARCHAR2(100) NOT NULL,
  EMAIL VARCHAR2(150) NOT NULL,
  PHONE VARCHAR2(20) NOT NULL,
  ROOM_TYPE VARCHAR2(20) NOT NULL REFERENCES HH_ROOM_TYPES(ROOM_TYPE),
  CHECK_IN DATE NOT NULL,
  CHECK_OUT DATE NOT NULL,
  GUESTS NUMBER(1) NOT NULL CHECK (GUESTS BETWEEN 1 AND 6),
  NIGHTLY_RATE NUMBER(10,2) NOT NULL,
  NIGHTS NUMBER(3) NOT NULL CHECK (NIGHTS BETWEEN 1 AND 60),
  TOTAL_AMOUNT NUMBER(12,2) NOT NULL,
  PAYMENT_METHOD VARCHAR2(20) NOT NULL,
  SPECIAL_REQUESTS VARCHAR2(500),
  STATUS VARCHAR2(20) DEFAULT 'CONFIRMED' NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT HH_BOOKING_DATES_CK CHECK (CHECK_OUT > CHECK_IN),
  CONSTRAINT HH_BOOKING_STATUS_CK CHECK (STATUS IN ('CONFIRMED','CANCELLED','COMPLETED')),
  CONSTRAINT HH_PAYMENT_METHOD_CK CHECK (PAYMENT_METHOD IN ('PAY_AT_HOTEL','UPI_AT_HOTEL','CARD_AT_HOTEL'))
);
CREATE INDEX HH_BOOKINGS_AVAIL_IDX ON HH_BOOKINGS (ROOM_TYPE, STATUS, CHECK_IN, CHECK_OUT);

